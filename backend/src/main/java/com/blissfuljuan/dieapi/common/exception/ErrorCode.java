package com.blissfuljuan.dieapi.common.exception;

/**
 * Every stable, machine-readable error code of the API. The constant name IS the code written to the {@code code}
 * member of the problem body, so renaming a constant is a breaking API change. Clients branch on these values.
 * Add a new constant here (and nothing else) when a new business failure needs its own code.
 *
 * <p>Failures that do not name a code (plain {@code ResponseStatusException}, container errors) get a code derived
 * from their HTTP status instead; see {@code ProblemDetails.codeFor}.
 */
